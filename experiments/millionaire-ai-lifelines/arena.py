"""Paired Monte Carlo lifeline decision experiment. No LLM/API calls.

The questions are readable trivia, but the shared answer engine's evidence is sampled
from a controlled distribution, rather than generated by a language model. All six
policies receive identical question/evidence/lifeline outcomes for each seed.
"""
from __future__ import annotations
import argparse, csv, hashlib, json, math, random
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path
from statistics import mean, median
import numpy as np
from sklearn.linear_model import LogisticRegression
from quiz_bank import BANK

AMOUNTS=(100,200,300,500,1000,2000,4000,8000,16000,32000,64000,125000,250000,500000,1000000)
NAMES=('Swagger','Flash','Chorus','Switch','Anchor','Compass')
ALPHABET='ABCD'

def softmax(logits):
    x=np.asarray(logits,dtype=float)
    z=np.exp(x-max(x)); return (z/z.sum()).tolist()

def signal(rng, correct, difficulty):
    vals=[rng.gauss(0,1.03) for _ in range(4)]
    vals[correct]+=3.05-2.45*difficulty
    return softmax(vals)

def safe_at(won):
    return 32000 if won>=32000 else (1000 if won>=1000 else 0)

def train_calibrator(seed=724, samples=16000):
    rng=random.Random(seed)
    X=[];y=[]
    for j in range(samples):
        difficulty=rng.uniform(0,1)
        label=rng.randrange(4)
        probs=signal(rng,label,difficulty)
        mx=max(probs)
        X.append([math.log(mx/(1-mx)),difficulty]); y.append(int(probs.index(mx)==label))
    model=LogisticRegression(max_iter=250,random_state=seed)
    model.fit(X,y)
    return model

def calibrate(model, raw, difficulty):
    top=max(raw); a=min(.99999,max(.00001,top))
    z=float(model.intercept_[0]+model.coef_[0,0]*math.log(a/(1-a))+model.coef_[0,1]*difficulty)
    p=1/(1+math.exp(-z))
    j=raw.index(top)
    others=sum(raw)-top
    return [p if k==j else (1-p)*raw[k]/others for k in range(4)]

def stable_rng(seed, question, lifeline):
    val=int(hashlib.sha256(f'{seed}:{question}:{lifeline}'.encode()).hexdigest()[:15],16)
    return random.Random(val)

def lifeline_material(seed, q_index, correct, difficulty):
    rr=stable_rng(seed,q_index,'fifty')
    removed=rr.sample([j for j in range(4) if j!=correct],2)
    # Some groups share a confident misconception. Audience votes are correlated.
    rr=stable_rng(seed,q_index,'audience')
    reliable=rr.random()>=.18
    audience_true=.87-.40*difficulty
    if reliable:
        vote_probs=[(1-audience_true)/3]*4; vote_probs[correct]=audience_true
    else:
        wrong=rr.choice([j for j in range(4) if j!=correct]);vote_probs=[.085]*4
        vote_probs[correct]=.065;vote_probs[wrong]=.68
        # normalize intentional probabilities (sum 1)
        sm=sum(vote_probs);vote_probs=[v/sm for v in vote_probs]
    votes=rr.choices(range(4),weights=vote_probs,k=40)
    counts=[votes.count(j) for j in range(4)]
    rr=stable_rng(seed,q_index,'friend')
    p_friend=.88-.39*difficulty
    friend=correct if rr.random()<p_friend else rr.choice([j for j in range(4) if j!=correct])
    return {'removed':removed,'audience':counts,'audience_reliable':reliable,'friend':friend}

def audience_loglike(counts,hypothesis,difficulty,weight=.17):
    p=.87-.40*difficulty
    def loglike(v):return sum(c*math.log(max(v,1e-8)) for c,v in zip(counts,v))
    fair=[(1-p)/3]*4;fair[hypothesis]=p
    logpieces=[math.log(.82)+loglike(fair)]
    for wrong in range(4):
        if wrong==hypothesis:continue
        bad=[.085]*4;bad[hypothesis]=.065;bad[wrong]=.68
        s=sum(bad);bad=[v/s for v in bad]
        logpieces.append(math.log(.18/3)+loglike(bad))
    peak=max(logpieces)
    return weight*(peak+math.log(sum(math.exp(v-peak) for v in logpieces)))

def update_belief(beliefs,lifeline,material,difficulty,policy):
    p=list(beliefs)
    if lifeline=='50:50':
        for j in material['removed']:p[j]=0
        # Correct answer never removed. Conditional reweighting.
    elif lifeline=='AUDIENCE':
        votes=material['audience']
        if policy=='Chorus':
            # Deliberately wrong: treats all 40 correlated votes as independent.
            p=[p[i]*(max(votes[i],1)/40)**5 for i in range(4)]
        else:
            likelihoods=[audience_loglike(votes,i,difficulty) for i in range(4)]
            pivot=max(likelihoods)
            p=[p[i]*math.exp(likelihoods[i]-pivot) for i in range(4)]
    elif lifeline=='FRIEND':
        claimed=material['friend']; reliab=.88-.39*difficulty
        p=[p[i]*(reliab if i==claimed else (1-reliab)/3) for i in range(4)]
    s=sum(p)
    return [x/s for x in p] if s>0 else list(beliefs)

@dataclass
class Player:
    policy:str
    available:set=field(default_factory=lambda:{'50:50','AUDIENCE','FRIEND'})
    won:int=0
    final:int=0
    status:str='playing'
    used:Counter=field(default_factory=Counter)
    steps:int=0
    correct:int=0
    lifelines:int=0
    log:list=field(default_factory=list)

def choose_action(policy,beliefs,position,won,available,allow_help=True):
    p=max(beliefs); prize=AMOUNTS[position];safe=safe_at(won)
    walk=won; answer_ev=p*prize+(1-p)*safe
    if policy=='Swagger':return 'ANSWER','always answers'
    if policy=='Flash':
        inflated=min(.99,p+.22)
        if allow_help and 'FRIEND' in available and inflated<.79 and position>=5:
            return 'FRIEND','asks only when even inflated confidence is low'
        return 'ANSWER',f'overconfident: treats {p:.0%} as {inflated:.0%}'
    if policy=='Chorus':
        if allow_help and 'AUDIENCE' in available and p<.91:
            return 'AUDIENCE','puts immediate trust in the crowd'
        if won>0 and p<.46:return 'WALK','only walks in extreme doubt'
        return 'ANSWER','follows popular or initial answer'
    if policy=='Switch':
        if allow_help and '50:50' in available and p<.80 and position>=2:
            return '50:50','uses elimination at the first notable uncertainty'
        if allow_help and 'FRIEND' in available and p<.54:
            return 'FRIEND','calls friend after 50:50 cannot resolve doubt'
        if won>0 and p<.61:return 'WALK','fixed confidence threshold'
        return 'ANSWER','fixed threshold permits guess'
    if policy=='Anchor':
        if allow_help and 'FRIEND' in available and p<.85 and position>=4:
            return 'FRIEND','asks the trusted friend'
        if allow_help and '50:50' in available and p<.77 and position>=6:
            return '50:50','eliminates two options'
        if won>0 and p<.80:return 'WALK','protects banked winnings at a fixed threshold'
        return 'ANSWER','confident enough to risk'
    # Compass: one-step expected value with explicit preservation penalty.
    if policy=='Compass':
        if allow_help and available:
            delta=prize-safe
            best=None
            for ll,gain in [('50:50',.42),('FRIEND',.38),('AUDIENCE',.30)]:
                if ll not in available:continue
                estimated_gain=(1-p)*gain*delta
                preserve_cost=(.09+.08*(14-position)/14)*delta
                net=estimated_gain-preserve_cost
                if best is None or net>best[1]:best=(ll,net)
            # Use only when the information is likely to affect a decision.
            if best and best[1]>0 and (p<.81 or answer_ev<walk):
                return best[0],f'estimated information gain exceeds lifeline preservation cost by ${best[1]:,.0f}'
        if won>0 and walk>answer_ev:
            return 'WALK',f'expected guess ${answer_ev:,.0f} below guaranteed walk ${walk:,.0f}'
        return 'ANSWER',f'expected guess ${answer_ev:,.0f} >= guaranteed walk ${walk:,.0f}'
    raise ValueError(policy)

def episode_questions(seed):
    rng=stable_rng(seed,999,'questions')
    # Fifteen varied, original multiple-choice questions; no natural-language inference performed.
    pools=[rng.sample(list(BANK[d]),5) for d in range(3)]
    return pools[0]+pools[1]+pools[2]

def play(seed,policy,model,allow_help=True,detail=False):
    qs=episode_questions(seed)
    player=Player(policy)
    for idx,question in enumerate(qs):
        difficulty=(idx+.5)/15
        rng=stable_rng(seed,idx,'answer-signal')
        raw=signal(rng,question.correct,difficulty)
        beliefs=calibrate(model,raw,difficulty)
        material=lifeline_material(seed,idx,question.correct,difficulty)
        initial_choice=max(range(4),key=lambda i:beliefs[i])
        used_here=set()
        for tries in range(4):
            action,reason=choose_action(policy,beliefs,idx,player.won,player.available,allow_help)
            before=max(beliefs)
            item={'question_number':idx+1,'amount':AMOUNTS[idx],'question':question.prompt,
                  'options':list(question.options),'correct_index':question.correct,
                  'agent':policy,'beliefs':[round(v,5) for v in beliefs],
                  'estimated_confidence':round(before,5),'choice':max(range(4),key=lambda i:beliefs[i]),
                  'action':action,'reason':reason,'won_before':player.won,'safe_before':safe_at(player.won),
                  'lifelines_remaining':sorted(player.available)}
            if action in ('50:50','AUDIENCE','FRIEND') and action not in used_here and action in player.available:
                player.available.remove(action);player.used[action]+=1;player.lifelines+=1
                used_here.add(action)
                item['help']={'removed':material['removed']} if action=='50:50' else ({'counts':material['audience'],'correlated_misconception':not material['audience_reliable']} if action=='AUDIENCE' else {'suggested_index':material['friend']})
                new=update_belief(beliefs,action,material,difficulty,policy)
                item['beliefs_after']=[round(v,5) for v in new]
                if detail:player.log.append(item)
                beliefs=new
                continue
            if action=='WALK':
                player.final=player.won;player.status='walked'
                item['result']='WALK';item['paid']=player.final
                if detail:player.log.append(item)
                return player
            chosen=max(range(4),key=lambda i:beliefs[i]);success=chosen==question.correct
            player.steps+=1;player.correct+=int(success)
            item['choice']=chosen;item['result']='CORRECT' if success else 'WRONG'
            if success:
                player.won=AMOUNTS[idx];item['paid']=player.won
                if detail:player.log.append(item)
                break
            else:
                player.final=safe_at(player.won);player.status='wrong';item['paid']=player.final
                if detail:player.log.append(item)
                return player
        else:raise RuntimeError('action loop exhausted')
    player.final=player.won;player.status='millionaire'
    return player

def csv_write(path,rows):
    if not rows:return
    path.parent.mkdir(parents=True,exist_ok=True)
    with path.open('w',newline='',encoding='utf-8') as f:
        w=csv.DictWriter(f,fieldnames=list(rows[0]));w.writeheader();w.writerows(rows)

def brier(pred,y):return mean((float(p)-int(a))**2 for p,a in zip(pred,y))

def ece(pred,y,bins=10):
    total=len(pred);v=0
    for ix in range(bins):
        ar=[(p,t) for p,t in zip(pred,y) if min(int(p*bins),bins-1)==ix]
        if ar:v+=len(ar)/total*abs(mean(p for p,_ in ar)-mean(t for _,t in ar))
    return v

def bootstrap_paired(diffs, seed=88, repeats=1500):
    rng=np.random.default_rng(seed);a=np.array(diffs,dtype=float)
    draw=rng.integers(0,len(a),size=(repeats,len(a)))
    return [round(float(np.quantile(a[draw].mean(axis=1),t)),2) for t in (.025,.975)]

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--episodes',type=int,default=1200)
    ap.add_argument('--seed',type=int,default=2026)
    ap.add_argument('--output',default='results')
    ap.add_argument('--featured-seed',type=int,default=42)
    args=ap.parse_args()
    out=Path(args.output);out.mkdir(parents=True,exist_ok=True)
    model=train_calibrator()
    samples=[];pred=[];actual=[]
    for e in range(4500):
        difficulty=(e%15+.5)/15;truth=e%4;rng=stable_rng(e,41,'calibration')
        raw=signal(rng,truth,difficulty);b=calibrate(model,raw,difficulty)
        top=max(b);correct=int(b.index(top)==truth)
        samples.append({'seed':e,'round':e%15+1,'raw_conf':round(max(raw),5),'calibrated_conf':round(top,5),'inflated_conf':round(min(.99,top+.20),5),'correct':correct})
        pred.append(top);actual.append(correct)
    csv_write(out/'calibration.csv',samples)
    tournament=[];paired=[]; wins=Counter();money=defaultdict(list)
    for i in range(args.episodes):
        seed=args.seed+i
        row={'seed':seed}
        for name in NAMES:
            p=play(seed,name,model)
            row[f'{name}_payout']=p.final
            row[f'{name}_stage']=p.steps
            row[f'{name}_status']=p.status
            row[f'{name}_lifelines']=p.lifelines
            money[name].append(p.final)
            if p.final>=1_000_000:wins[name]+=1
        tournament.append(row)
        with_help=play(seed,'Compass',model)
        no_help=play(seed,'Compass',model,allow_help=False)
        paired.append({'seed':seed,'full_payout':with_help.final,'no_lifelines_payout':no_help.final,'difference':with_help.final-no_help.final,'full_reached':with_help.steps,'no_reached':no_help.steps})
    csv_write(out/'tournaments.csv',tournament)
    csv_write(out/'lifeline_ablation.csv',paired)
    summary={'episodes':args.episodes,'seed_start':args.seed,'calibration':{'heldout_n':len(samples),'accuracy':round(mean(actual),4),'mean_conf':round(mean(pred),4),'brier':round(brier(pred,actual),4),'ece_10':round(ece(pred,actual),4),'inflated_brier':round(brier([min(.99,p+.20) for p in pred],actual),4),'inflated_ece_10':round(ece([min(.99,p+.20) for p in pred],actual),4)},'policies':{},'ablation':{}}
    for name in NAMES:
        payouts=money[name]
        summary['policies'][name]={'mean_payout':round(mean(payouts),2),'median_payout':median(payouts),'payout_1000_or_more':round(mean(v>=1000 for v in payouts),4),'payout_32000_or_more':round(mean(v>=32000 for v in payouts),4),'millionaire_count':wins[name],'mean_steps':round(mean(r[f'{name}_stage'] for r in tournament),2),'mean_lifelines_used':round(mean(r[f'{name}_lifelines'] for r in tournament),3),'walk_rate':round(mean(r[f'{name}_status']=='walked' for r in tournament),3)}
    diffs=[x['difference'] for x in paired]
    summary['ablation']={'mean_difference':round(mean(diffs),2),'median_difference':median(diffs),'bootstrap95':bootstrap_paired(diffs),'positive_pair_rate':round(mean(x>0 for x in diffs),3),'negative_pair_rate':round(mean(x<0 for x in diffs),3)}
    (out/'summary.json').write_text(json.dumps(summary,indent=2),encoding='utf-8')
    featured={'seed':args.featured_seed,'players':[],'payouts':{},'summary':summary}
    for name in NAMES:
        p=play(args.featured_seed,name,model,detail=True)
        featured['players'].append({'name':name,'final':p.final,'status':p.status,'events':p.log})
        featured['payouts'][name]=p.final
    (out/'featured.json').write_text(json.dumps(featured,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(summary,indent=2))

if __name__=='__main__':main()
